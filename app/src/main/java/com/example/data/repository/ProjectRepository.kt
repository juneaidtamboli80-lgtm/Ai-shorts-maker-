    suspend fun createProjectFromUri(uri: Uri, customName: String? = null): ProjectEntity = withContext(Dispatchers.IO) {
        val videoInfo = extractVideoInfo(uri)
        val name = customName ?: "Project_${System.currentTimeMillis() % 10000}"
        val project = ProjectEntity(
            name = name,
            videoUri = uri.toString(),
            durationMs = videoInfo.durationMs.coerceAtLeast(1000L),
            width = if (videoInfo.width > 0) videoInfo.width else 1080,
            height = if (videoInfo.height > 0) videoInfo.height else 1920,
            fps = videoInfo.fps,
            rotation = videoInfo.rotation,
            trimStartMs = 0L,
            trimEndMs = videoInfo.durationMs.coerceAtLeast(1000L),
            selectedSectionStartMs = 0L,
            selectedSectionEndMs = videoInfo.durationMs.coerceAtLeast(1000L),
            aspectRatio = if (videoInfo.width > videoInfo.height) AspectRatio.RATIO_16_9 else AspectRatio.RATIO_9_16
        )
        projectDao.insertProject(project)
        project
    }

    suspend fun createSampleProject(templateIndex: Int = 0): ProjectEntity = withContext(Dispatchers.IO) {
        val templates = SampleVideoProvider.getSampleTemplates()
        val template = templates.getOrElse(templateIndex) { templates.first() }
        val sampleVideoFile = SampleVideoProvider.generateOrGetSampleVideoFile(context, templateIndex)

        val project = ProjectEntity(
            name = template.title,
            videoUri = Uri.fromFile(sampleVideoFile).toString(),
            videoPath = sampleVideoFile.absolutePath,
            durationMs = template.durationMs,
            width = template.width,
            height = template.height,
            fps = 30f,
            trimStartMs = 0L,
            trimEndMs = template.durationMs,
            selectedSectionStartMs = 0L,
            selectedSectionEndMs = template.durationMs,
            aspectRatio = AspectRatio.RATIO_9_16
        )
        projectDao.insertProject(project)

        // Insert default captions
        val captionEntities = template.defaultCaptions.map { cap ->
            CaptionEntity(
                id = cap.id,
                projectId = project.id,
                startMs = cap.startMs,
                endMs = cap.endMs,
                text = cap.text,
                wordsJson = Converters.serializeWords(cap.words),
                styleJson = Converters.serializeSubtitleStyle(cap.style),
                isAutoGenerated = true
            )
        }
        captionDao.insertCaptions(captionEntities)

        // Insert default text layers
        template.defaultTextLayers.forEach { textLayer ->
            layerDao.insertTextLayer(
                TextLayerEntity(
                    id = textLayer.id,
                    projectId = project.id,
                    text = textLayer.text,
                    startMs = textLayer.startMs,
                    endMs = textLayer.endMs,
                    posX = textLayer.posX,
                    posY = textLayer.posY,
                    scale = textLayer.scale,
                    rotationDeg = textLayer.rotationDeg,
                    opacity = textLayer.opacity,
                    fontFamily = textLayer.fontFamily,
                    fontSizeSp = textLayer.fontSizeSp,
                    isBold = textLayer.isBold,
                    isItalic = textLayer.isItalic,
                    colorHex = textLayer.colorHex,
                    strokeColorHex = textLayer.strokeColorHex,
                    strokeWidth = textLayer.strokeWidth,
                    hasStroke = textLayer.hasStroke,
                    shadowColorHex = textLayer.shadowColorHex,
                    shadowRadius = textLayer.shadowRadius,
                    backgroundColorHex = textLayer.backgroundColorHex,
                    backgroundOpacity = textLayer.backgroundOpacity,
                    animation = textLayer.animation,
                    keyframesJson = Converters.serializeKeyframes(textLayer.keyframes),
                    attachedTrackingObjectId = textLayer.attachedTrackingObjectId
                )
            )
        }

        // Insert default tracking objects
        template.defaultTracking.forEach { track ->
            layerDao.insertTrackingObject(
                TrackingObjectEntity(
                    id = track.id,
                    projectId = project.id,
                    label = track.label,
                    isFace = track.isFace,
                    startMs = track.startMs,
                    endMs = track.endMs,
                    boundingBoxesJson = Converters.serializeBoundingBoxes(track.boundingBoxes),
                    sensitivity = track.sensitivity,
                    smoothing = track.smoothing,
                    offsetX = track.offsetX,
                    offsetY = track.offsetY,
                    attachmentType = track.attachmentType,
                    attachedText = track.attachedText,
                    attachedStickerEmoji = track.attachedStickerEmoji
                )
            )
        }

        project
    }

