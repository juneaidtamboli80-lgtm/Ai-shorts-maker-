    suspend fun duplicateProject(projectId: String): ProjectEntity? = withContext(Dispatchers.IO) {
        val original = projectDao.getProjectById(projectId) ?: return@withContext null
        val newId = java.util.UUID.randomUUID().toString()
        val duplicated = original.copy(
            id = newId,
            name = "${original.name} (Copy)",
            createdAt = System.currentTimeMillis(),
            modifiedAt = System.currentTimeMillis()
        )
        projectDao.insertProject(duplicated)

        // Copy captions
        val captions = captionDao.getCaptionsForProject(projectId)
        captionDao.insertCaptions(captions.map { it.copy(id = java.util.UUID.randomUUID().toString(), projectId = newId) })

        // Copy layers
        val textLayers = layerDao.getTextLayersForProject(projectId)
        textLayers.forEach { layerDao.insertTextLayer(it.copy(id = java.util.UUID.randomUUID().toString(), projectId = newId)) }

        val stickerLayers = layerDao.getStickerLayersForProject(projectId)
        stickerLayers.forEach { layerDao.insertStickerLayer(it.copy(id = java.util.UUID.randomUUID().toString(), projectId = newId)) }

        val trackingObjects = layerDao.getTrackingObjectsForProject(projectId)
        trackingObjects.forEach { layerDao.insertTrackingObject(it.copy(id = java.util.UUID.randomUUID().toString(), projectId = newId)) }

        duplicated
    }

