package com.example.data.database

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.model.*

@Entity(tableName = "projects")
data class ProjectEntity(
    @PrimaryKey val id: String = java.util.UUID.randomUUID().toString(),
    val name: String,
    val createdAt: Long = System.currentTimeMillis(),
    val modifiedAt: Long = System.currentTimeMillis(),
    val videoUri: String,
    val videoPath: String = "",
    val durationMs: Long,
    val width: Int = 1080,
    val height: Int = 1920,
    val fps: Float = 30f,
    val rotation: Int = 0,
    val trimStartMs: Long = 0L,
    val trimEndMs: Long = durationMs,
    val selectedSectionStartMs: Long = 0L,
    val selectedSectionEndMs: Long = durationMs,
    val aspectRatio: AspectRatio = AspectRatio.RATIO_9_16,
    val speed: Float = 1.0f,
    val volume: Float = 1.0f,
    val isMuted: Boolean = false,
    val effectsJson: String = "",
    val transitionType: TransitionType = TransitionType.NONE,
    val transitionDurationMs: Long = 500L,
    val isFavorite: Boolean = false,
    val thumbnailUri: String? = null
)

@Entity(
    tableName = "captions",
    foreignKeys = [
        ForeignKey(
            entity = ProjectEntity::class,
            parentColumns = ["id"],
            childColumns = ["projectId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("projectId")]
)
data class CaptionEntity(
    @PrimaryKey val id: String = java.util.UUID.randomUUID().toString(),
    val projectId: String,
    val startMs: Long,
    val endMs: Long,
    val text: String,
    val wordsJson: String = "[]",
    val styleJson: String = "",
    val isAutoGenerated: Boolean = true
)

@Entity(
    tableName = "text_layers",
    foreignKeys = [
        ForeignKey(
            entity = ProjectEntity::class,
            parentColumns = ["id"],
            childColumns = ["projectId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("projectId")]
)
data class TextLayerEntity(
    @PrimaryKey val id: String = java.util.UUID.randomUUID().toString(),
    val projectId: String,
    val text: String,
    val startMs: Long,
    val endMs: Long,
    val posX: Float = 0.5f,
    val posY: Float = 0.5f,
    val scale: Float = 1.0f,
    val rotationDeg: Float = 0f,
    val opacity: Float = 1.0f,
    val fontFamily: String = "SansSerif",
    val fontSizeSp: Float = 24f,
    val isBold: Boolean = true,
    val isItalic: Boolean = false,
    val colorHex: String = "#FFFFFF",
    val strokeColorHex: String = "#000000",
    val strokeWidth: Float = 2f,
    val hasStroke: Boolean = false,
    val shadowColorHex: String = "#000000",
    val shadowRadius: Float = 4f,
    val backgroundColorHex: String = "#000000",
    val backgroundOpacity: Float = 0f,
    val animation: LayerAnimationType = LayerAnimationType.NONE,
    val keyframesJson: String = "[]",
    val attachedTrackingObjectId: String? = null
)

@Entity(
    tableName = "sticker_layers",
    foreignKeys = [
        ForeignKey(
            entity = ProjectEntity::class,
            parentColumns = ["id"],
            childColumns = ["projectId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("projectId")]
)
data class StickerLayerEntity(
    @PrimaryKey val id: String = java.util.UUID.randomUUID().toString(),
    val projectId: String,
    val stickerType: String = "EMOJI",
    val emojiOrText: String = "🔥",
    val customImageUri: String? = null,
    val startMs: Long = 0L,
    val endMs: Long = 5000L,
    val posX: Float = 0.5f,
    val posY: Float = 0.35f,
    val scale: Float = 1.0f,
    val rotationDeg: Float = 0f,
    val opacity: Float = 1.0f,
    val keyframesJson: String = "[]",
    val attachedTrackingObjectId: String? = null
)

@Entity(
    tableName = "tracking_objects",
    foreignKeys = [
        ForeignKey(
            entity = ProjectEntity::class,
            parentColumns = ["id"],
            childColumns = ["projectId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("projectId")]
)
data class TrackingObjectEntity(
    @PrimaryKey val id: String = java.util.UUID.randomUUID().toString(),
    val projectId: String,
    val label: String = "Tracked Object",
    val isFace: Boolean = false,
    val startMs: Long = 0L,
    val endMs: Long = 5000L,
    val boundingBoxesJson: String = "[]",
    val sensitivity: Float = 0.7f,
    val smoothing: Float = 0.3f,
    val offsetX: Float = 0f,
    val offsetY: Float = -0.05f,
    val attachmentType: TrackedAttachmentType = TrackedAttachmentType.TEXT,
    val attachedText: String = "Target 🎯",
    val attachedStickerEmoji: String = "🔥"
)

@Entity(
    tableName = "audio_tracks",
    foreignKeys = [
        ForeignKey(
            entity = ProjectEntity::class,
            parentColumns = ["id"],
            childColumns = ["projectId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("projectId")]
)
data class AudioTrackEntity(
    @PrimaryKey val id: String = java.util.UUID.randomUUID().toString(),
    val projectId: String,
    val title: String,
    val uri: String? = null,
    val startTimelineMs: Long = 0L,
    val clipOffsetMs: Long = 0L,
    val durationMs: Long,
    val volume: Float = 0.8f,
    val fadeInMs: Long = 500L,
    val fadeOutMs: Long = 1000L,
    val isMuted: Boolean = false,
    val isOriginalAudio: Boolean = false,
    val isVoiceOver: Boolean = false
)
