package com.example.model

enum class CaptionAnimation(val label: String) {
    NONE("Static"),
    POP("Pop In"),
    BOUNCE("Bouncy Pop"),
    SCALE_ACTIVE("Scale Active Word"),
    KARAOKE_HIGHLIGHT("Karaoke Glow"),
    FADE("Smooth Fade")
}

enum class SubtitleAlignment(val label: String) {
    LEFT("Left"),
    CENTER("Center"),
    RIGHT("Right")
}

data class WordTiming(
    val word: String,
    val startMs: Long,
    val endMs: Long
)

data class SubtitleStyle(
    val fontFamilyName: String = "SansSerif",
    val fontSizeSp: Float = 22f,
    val isBold: Boolean = true,
    val isItalic: Boolean = false,
    val isUppercase: Boolean = false,
    val alignment: SubtitleAlignment = SubtitleAlignment.CENTER,
    val textColorHex: String = "#FFFFFF",
    val activeWordColorHex: String = "#FDE047", // Yellow highlight for active word
    val backgroundColorHex: String = "#000000",
    val backgroundOpacity: Float = 0.5f,
    val hasBackground: Boolean = true,
    val strokeColorHex: String = "#000000",
    val strokeWidth: Float = 3f,
    val hasStroke: Boolean = true,
    val shadowColorHex: String = "#000000",
    val shadowRadius: Float = 4f,
    val positionYRatio: Float = 0.82f, // 0 (top) to 1 (bottom)
    val letterSpacingSp: Float = 0.5f,
    val lineSpacingMultiplier: Float = 1.1f,
    val maxCharsPerLine: Int = 28,
    val animation: CaptionAnimation = CaptionAnimation.SCALE_ACTIVE,
    val activeWordScale: Float = 1.25f
)

data class CaptionSegment(
    val id: String = java.util.UUID.randomUUID().toString(),
    val projectId: String,
    val startMs: Long,
    val endMs: Long,
    val text: String,
    val words: List<WordTiming> = emptyList(),
    val style: SubtitleStyle = SubtitleStyle(),
    val isAutoGenerated: Boolean = true
) {
    fun containsTime(timeMs: Long): Boolean {
        return timeMs in startMs..endMs
    }

    fun getActiveWordIndex(timeMs: Long): Int {
        if (words.isEmpty()) return -1
        return words.indexOfFirst { timeMs in it.startMs..it.endMs }
    }
}
